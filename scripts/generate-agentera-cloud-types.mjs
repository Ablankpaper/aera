import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format } from "prettier";

const scriptPath = fileURLToPath(import.meta.url);
export const projectRoot = resolve(dirname(scriptPath), "..");
export const contractPath = resolve(
  projectRoot,
  "contracts/agentera-cloud.openapi.yaml",
);
export const generatedPath = resolve(
  projectRoot,
  "src/shared/agentera-cloud-api.generated.ts",
);

export async function renderAgenteraCloudTypes() {
  const contract = await readFile(contractPath);
  const contractSha256 = createHash("sha256").update(contract).digest("hex");
  const ast = await openapiTS(contract, {
    alphabetize: true,
    exportType: true,
    immutable: true,
  });
  const unformatted = `/**
 * Generated from contracts/agentera-cloud.openapi.yaml.
 * Contract SHA-256: ${contractSha256}
 * Do not edit this file directly.
 */

${astToString(ast)}`;
  const output = await format(unformatted, { parser: "typescript" });
  return { contractSha256, output };
}

export async function generateAgenteraCloudTypes() {
  const rendered = await renderAgenteraCloudTypes();
  await mkdir(dirname(generatedPath), { recursive: true });
  await writeFile(generatedPath, rendered.output, "utf8");
  return rendered;
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  const { contractSha256 } = await generateAgenteraCloudTypes();
  process.stdout.write(
    `Generated ${generatedPath} from AgentEra cloud contract ${contractSha256}.\n`,
  );
}
